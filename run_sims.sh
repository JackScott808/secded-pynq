#!/usr/bin/env bash
#
# Build and run every testbench with Verilator, saving each one's output to
# reports/<testbench>.log and writing reports/SUMMARY.md.
#
# The logs are committed: they are the record of what the tests actually printed,
# with the Verilator version, commit and command that produced them.
#
# Usage:
#   ./run_sims.sh              run every testbench
#   ./run_sims.sh tb_decoder   run just one (or several, named)

set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RTL_DIR="$ROOT/model/verilog"
REPORT_DIR="$ROOT/reports"

ALL_TESTS=(tb_syndrome tb_encoder tb_decoder tb_crosscheck tb_bist_sweep tb_bist_top)
TESTS=("${@:-}")
[ -z "${TESTS[0]}" ] && TESTS=("${ALL_TESTS[@]}")

VERILATOR_FLAGS=(--binary --timing -Wall -y . --quiet)
# Testbenches end with their own verdict line: "all tests passed" from most,
# "all 5000 vectors passed" from tb_crosscheck. Anything else is a failure.
PASS_PATTERN='^all .*passed'
FAIL_PATTERN='FAIL|%Error|there were [0-9]+ error'
VERDICT_PATTERN='^(all |FAIL|there were )' 

mkdir -p "$REPORT_DIR"
cd "$RTL_DIR" || exit 1

verilator_version="$(verilator --version 2>&1)"
if git_describe="$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null)"; then
    if ! git -C "$ROOT" diff --quiet || ! git -C "$ROOT" diff --cached --quiet; then
        git_describe="$git_describe-dirty"
    fi
else
    git_describe="not a git repo"
fi
run_date="$(date -u '+%Y-%m-%dT%H:%M:%SZ')"

declare -a summary_rows=()
overall_status=0

for tb in "${TESTS[@]}"; do
    log="$REPORT_DIR/$tb.log"
    build_dir="obj_dir/$tb"
    mkdir -p "$build_dir"   # Verilator will not create a nested --Mdir itself
    build_cmd=(verilator "${VERILATOR_FLAGS[@]}" --Mdir "$build_dir" --top-module "$tb" "$tb.sv")

    {
        echo "# $tb"
        echo "# date:      $run_date"
        echo "# verilator: $verilator_version"
        echo "# commit:    $git_describe"
        echo "# host:      $(uname -srm)"
        echo "# build:     ${build_cmd[*]}"
        echo "# run:       ./$build_dir/V$tb   (from model/verilog)"
        echo
    } > "$log"

    echo "==> $tb: building"
    if ! build_output="$("${build_cmd[@]}" 2>&1)"; then
        {
            echo "BUILD FAILED"
            echo
            echo "$build_output"
        } >> "$log"
        echo "    build failed, see $log"
        summary_rows+=("$tb|BUILD FAILED|-|-")
        overall_status=1
        continue
    fi
    # Warnings matter even when the build succeeds, so keep them.
    if [ -n "$build_output" ]; then
        {
            echo "--- build warnings ---"
            echo "$build_output"
            echo "--- end build warnings ---"
            echo
        } >> "$log"
    fi

    echo "==> $tb: running"
    start="$(perl -MTime::HiRes=time -e 'print time')"
    run_output="$("./$build_dir/V$tb" 2>&1)"
    run_exit=$?
    duration="$(perl -MTime::HiRes=time -e "printf '%.2f', time - $start")s"

    echo "$run_output" >> "$log"

    # A testbench prints its own verdict and exits 0 either way, so the verdict
    # string decides pass or fail, not the exit code alone.
    verdict="$(echo "$run_output" | grep -m1 -E "$VERDICT_PATTERN")"
    if [ "$run_exit" -ne 0 ]; then
        status="CRASHED (exit $run_exit)"
        overall_status=1
    elif echo "$run_output" | grep -qE "$FAIL_PATTERN"; then
        status="FAIL"
        overall_status=1
    elif echo "$run_output" | grep -qE "$PASS_PATTERN"; then
        status="PASS"
    else
        status="NO VERDICT"
        overall_status=1
    fi
    [ -z "$verdict" ] && verdict="(no verdict line)"

    {
        echo
        echo "# result:   $status"
        echo "# exit:     $run_exit"
        echo "# duration: $duration"
    } >> "$log"

    echo "    $status ($duration) -> reports/$tb.log"
    summary_rows+=("$tb|$status|$duration|$verdict")
done

{
    echo "# Simulation reports"
    echo
    echo "Generated by \`run_sims.sh\`. One log per testbench in this folder."
    echo
    echo "| Run (UTC) | Verilator | Commit |"
    echo "|---|---|---|"
    echo "| $run_date | $verilator_version | $git_describe |"
    echo
    echo "| Testbench | Result | Time | Verdict |"
    echo "|---|---|---|---|"
    for row in "${summary_rows[@]}"; do
        IFS='|' read -r name status time last <<< "$row"
        echo "| \`$name\` | $status | $time | $last |"
    done
} > "$REPORT_DIR/SUMMARY.md"

echo
if [ "$overall_status" -eq 0 ]; then
    echo "All testbenches passed. Summary: reports/SUMMARY.md"
else
    echo "Some testbenches did not pass. Summary: reports/SUMMARY.md"
fi
exit "$overall_status"
